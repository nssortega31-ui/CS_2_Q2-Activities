def add_numbers(num1, num2):
    sum_val = num1 + num2
    return sum_val

def subtract_numbers(num1, num2):
    difference = num1 - num2
    return difference

def multiply_numbers(num1, num2):
    product = num1 * num2
    return product

def divide_numbers(num1, num2):
    if num2 == 0:
        return "Error! Cannot divide by zero"
    quotient = num1 / num2
    return quotient

# Get user input
num1 = float(input("Enter First Number: "))
num2 = float(input("Enter Second Number: "))

print("""Choose the type of Operation:
Addition - 1
Subtraction - 2
Multiplication - 3
Division - 4""")

operation = int(input("Enter operation (1-4): "))

# Execute selected operation
if operation == 1:
    print("Result:", add_numbers(num1, num2))
elif operation == 2:
    print("Result:", subtract_numbers(num1, num2))
elif operation == 3:
    print("Result:", multiply_numbers(num1, num2))
elif operation == 4:
    print("Result:", divide_numbers(num1, num2))
else:
    print("Invalid operation selection.")

